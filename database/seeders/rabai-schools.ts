function getDemoYearValues(
  school: RabaiSchool,
  schoolIndex: number,
  yearIndex: number,
) {
  const typeBase =
    school.institutionType === "SENIOR_SECONDARY"
      ? 180
      : school.institutionType === "JUNIOR_SECONDARY"
        ? 90
        : 140;
  const ownershipOffset = school.ownershipType === "PRIVATE" ? -35 : 0;
  const studentCount = Math.max(
    35,
    typeBase + schoolIndex * 9 + ownershipOffset + yearIndex * 18,
  );
  const teacherBase =
    school.institutionType === "SENIOR_SECONDARY"
      ? 14
      : school.institutionType === "JUNIOR_SECONDARY"
        ? 6
        : 8;

  return {
    studentCount,
    teacherCount: teacherBase + (schoolIndex % 8) + yearIndex,
    classCount:
      school.institutionType === "SENIOR_SECONDARY"
        ? 4 + (schoolIndex % 4)
        : school.institutionType === "JUNIOR_SECONDARY"
          ? 3
          : 6 + (schoolIndex % 5),
  };
}

