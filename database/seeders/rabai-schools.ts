export function getRabaiWardSummaries(academicYearId: string) {
  const yearRows = rabaiSchoolYears.filter(
    (schoolYear) => schoolYear.academicYearId === academicYearId,
  );

  return Object.values(
    rabaiSchools.reduce<
      Record<
        string,
        {
          name: string;
          wardCode: string | null;
          county: string | null;
          countyCode: string | null;
          subCounty: string | null;
          subCountyCode: string | null;
          constituency: string | null;
          constituencyCode: string | null;
          schoolCount: number;
          publicSchools: number;
          privateSchools: number;
          primarySchools: number;
          juniorSecondarySchools: number;
          seniorSecondarySchools: number;
          studentCount: number;
          teacherCount: number;
        }
      >
    >(
      (acc, school) => {
        const ward = school.ward ?? "Not mapped";
        const year = yearRows.find((row) => row.schoolId === school.id);

        acc[ward] ??= {
          name: ward,
          wardCode: null,
          county: school.county,
          countyCode: null,
          subCounty: school.subCounty,
          subCountyCode: null,
          constituency: null,
          constituencyCode: null,
          schoolCount: 0,
          publicSchools: 0,
          privateSchools: 0,
          primarySchools: 0,
          juniorSecondarySchools: 0,
          seniorSecondarySchools: 0,
          studentCount: 0,
          teacherCount: 0,
        };

        acc[ward].schoolCount += 1;
        if (school.ownershipType === "PUBLIC") acc[ward].publicSchools += 1;
        if (school.ownershipType === "PRIVATE") acc[ward].privateSchools += 1;
        if (school.institutionType === "PRIMARY") acc[ward].primarySchools += 1;
        if (school.institutionType === "JUNIOR_SECONDARY") {
          acc[ward].juniorSecondarySchools += 1;
        }
        if (school.institutionType === "SENIOR_SECONDARY") {
          acc[ward].seniorSecondarySchools += 1;
        }
        acc[ward].studentCount += year?.studentCount ?? 0;
        acc[ward].teacherCount += year?.teacherCount ?? 0;

        return acc;
      },
      rabaiWards.reduce<
        Record<
          string,
          {
            name: string;
            wardCode: string | null;
            county: string | null;
            countyCode: string | null;
            subCounty: string | null;
            subCountyCode: string | null;
            constituency: string | null;
            constituencyCode: string | null;
            schoolCount: number;
            publicSchools: number;
            privateSchools: number;
            primarySchools: number;
            juniorSecondarySchools: number;
            seniorSecondarySchools: number;
            studentCount: number;
            teacherCount: number;
          }
        >
      >((acc, ward) => {
        acc[ward.wardName] = {
          name: ward.wardName,
          wardCode: ward.wardCode,
          county: ward.county,
          countyCode: ward.countyCode,
          subCounty: ward.subCounty,
          subCountyCode: ward.subCountyCode,
          constituency: ward.constituency,
          constituencyCode: ward.constituencyCode,
          schoolCount: 0,
          publicSchools: 0,
          privateSchools: 0,
          primarySchools: 0,
          juniorSecondarySchools: 0,
          seniorSecondarySchools: 0,
          studentCount: 0,
          teacherCount: 0,
        };

        return acc;
      }, {}),
    ),
  ).sort((a, b) =>
    a.name === "Not mapped"
      ? 1
      : b.name === "Not mapped"
        ? -1
        : a.name.localeCompare(b.name),
  );
}

